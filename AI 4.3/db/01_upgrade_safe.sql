SET DEFINE OFF
SET SERVEROUTPUT ON

-- helper: run a DDL statement, ignore "already exists" type errors so the script is re-runnable
CREATE OR REPLACE PROCEDURE ai_ddl (p_sql IN VARCHAR2) AS
BEGIN
    EXECUTE IMMEDIATE p_sql;
EXCEPTION
    WHEN OTHERS THEN
        -- -955 name in use | -1430 column exists | -1408 index exists | -2260/-2261 key exists
        IF SQLCODE IN (-955, -1430, -1408, -2260, -2261) THEN NULL; ELSE RAISE; END IF;
END;
/

--------------------------------------------------------------------------------
-- 1) Usage log: one row per AI call (chat answer, planner, voice, transliteration)
--------------------------------------------------------------------------------
BEGIN
    ai_ddl(q'[
        CREATE TABLE ai_usage_log (
            usage_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            user_id            NUMBER,
            session_id         VARCHAR2(100),
            provider_id        NUMBER,
            model_name         VARCHAR2(200),
            call_type          VARCHAR2(30),            -- ANSWER / PLAN / SUMMARY / TRANSCRIBE / TRANSLITERATE
            status             VARCHAR2(30),            -- OK / FAILED / RATE_LIMITED / CANCELLED
            prompt_tokens      NUMBER DEFAULT 0 NOT NULL,
            completion_tokens  NUMBER DEFAULT 0 NOT NULL,
            total_tokens       NUMBER DEFAULT 0 NOT NULL,
            cost_usd           NUMBER(14,6) DEFAULT 0 NOT NULL,
            latency_ms         NUMBER,
            rl_remaining_req   NUMBER,                  -- Groq header x-ratelimit-remaining-requests (per day)
            rl_remaining_tok   NUMBER,                  -- Groq header x-ratelimit-remaining-tokens  (per minute)
            rl_reset_req       VARCHAR2(30),
            rl_reset_tok       VARCHAR2(30),
            question_preview   VARCHAR2(400),
            error_message      VARCHAR2(4000)
        )]');
    ai_ddl('CREATE INDEX ai_usage_ix_time ON ai_usage_log (created_at, provider_id)');
    ai_ddl('CREATE INDEX ai_usage_ix_user ON ai_usage_log (user_id, created_at)');
END;
/

