-- * What it does:
--     1. Fixes the missing  POST /engine/chat/truncate  (Edit / Regenerate were failing with 404)
--     2. /engine/chat/messages now returns created_at (real message times)
--     3. New table AI_USAGE_LOG + views for credits / remaining limits
--     4. Limit + pricing columns on AI_PROVIDERS, quota/admin columns on AI_USERS
--     5. Schema-hint columns on AI_DATA_ENDPOINTS (makes answers accurate + cheap)
--     6. New REST handlers:  usage/log, usage/providers, usage/user/:user_id, usage/daily, usage/top
