-- 7) REST handlers (added to the existing module 'AI' -> /ords/aiagent/engine/...)
--------------------------------------------------------------------------------
BEGIN
    ------------------------------------------------------------------ bug fix
    -- POST chat/truncate  {user_id, session_id, keep_count}: keep only the first N messages (Edit / Regenerate)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'chat/truncate');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'chat/truncate', p_method => 'POST',
        p_source_type => 'plsql/block',
        p_source      => q'[
BEGIN
    DELETE FROM ai_chat_messages
     WHERE ROWID IN (
           SELECT rid FROM (
                  SELECT m.ROWID AS rid,
                         ROW_NUMBER() OVER (ORDER BY m.created_at,
                                                     CASE WHEN m.sender_role = 'user' THEN 0 ELSE 1 END,
                                                     m.ROWID) AS rn
                    FROM ai_chat_messages m
                   WHERE m.session_id = :session_id
                     AND EXISTS (SELECT 1 FROM ai_chat_sessions s
                                  WHERE s.session_id = m.session_id
                                    AND s.user_id = :user_id))
            WHERE rn > TO_NUMBER(:keep_count));
END;]');

    ------------------------------------------------------------------ messages now carry their time + metadata
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'chat/messages/:session_id');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'chat/messages/:session_id', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[
SELECT sender_role, content, created_at, provider_name, total_tokens, latency_ms
  FROM ai_chat_messages
 WHERE session_id = :session_id
 ORDER BY created_at, CASE WHEN sender_role = 'user' THEN 0 ELSE 1 END, ROWID]');

    ------------------------------------------------------------------ save: optional answer metadata (old app simply does not send it)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'chat/save');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'chat/save', p_method => 'POST',
        p_source_type => 'plsql/block',
        p_source      => q'[
BEGIN
    BEGIN
        INSERT INTO ai_chat_sessions (session_id, user_id, session_title)
        VALUES (:session_id, :user_id, :session_title);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;
    END;
    INSERT INTO ai_chat_messages (session_id, sender_role, content)
    VALUES (:session_id, 'user', :user_msg);
    INSERT INTO ai_chat_messages (session_id, sender_role, content, provider_name, total_tokens, latency_ms)
    VALUES (:session_id, 'ai', :ai_msg, :provider_name, :total_tokens, :latency_ms);
END;]');

    ------------------------------------------------------------------ endpoints: only active ones, plus schema hint
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'user-endpoints/:user_id');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'user-endpoints/:user_id', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[
SELECT e.endpoint_id, e.endpoint_name, e.rest_url, e.description, e.schema_hint, e.cache_seconds,
       NVL(e.is_active, 'Y') AS endpoint_active, NVL(a.is_active, 'Y') AS access_active
  FROM ai_data_endpoints e
  JOIN ai_user_access a ON e.endpoint_id = a.endpoint_id
 WHERE a.user_id = :user_id
   AND NVL(e.is_active, 'Y') = 'Y'
   AND NVL(a.is_active, 'Y') = 'Y']');

    ------------------------------------------------------------------ login audit with IP / browser (optional fields)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'logs/login');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'logs/login', p_method => 'POST',
        p_source_type => 'plsql/block',
        p_source      => q'[
BEGIN
    INSERT INTO ai_login_history (user_id, ip_address, user_agent)
    VALUES (:user_id, SUBSTR(:ip_address, 1, 64), SUBSTR(:user_agent, 1, 400));
END;]');

    ------------------------------------------------------------------ usage: write one AI call (cost computed from provider prices)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'usage/log');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'usage/log', p_method => 'POST',
        p_source_type => 'plsql/block',
        p_source      => q'[
DECLARE
    l_in  NUMBER := 0;
    l_out NUMBER := 0;
    l_pt  NUMBER := NVL(TO_NUMBER(:prompt_tokens), 0);
    l_ct  NUMBER := NVL(TO_NUMBER(:completion_tokens), 0);
BEGIN
    BEGIN
        SELECT NVL(price_in_per_m, 0), NVL(price_out_per_m, 0) INTO l_in, l_out
          FROM ai_providers WHERE provider_id = TO_NUMBER(:provider_id);
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;
    INSERT INTO ai_usage_log (user_id, session_id, provider_id, model_name, call_type, status,
                              prompt_tokens, completion_tokens, total_tokens, cost_usd, latency_ms,
                              rl_remaining_req, rl_remaining_tok, rl_reset_req, rl_reset_tok,
                              question_preview, error_message)
    VALUES (TO_NUMBER(:user_id), :session_id, TO_NUMBER(:provider_id), :model_name, :call_type, NVL(:status, 'OK'),
            l_pt, l_ct, NVL(TO_NUMBER(:total_tokens), l_pt + l_ct),
            ROUND(l_pt * l_in / 1e6 + l_ct * l_out / 1e6, 6), TO_NUMBER(:latency_ms),
            TO_NUMBER(:rl_remaining_req), TO_NUMBER(:rl_remaining_tok), :rl_reset_req, :rl_reset_tok,
            SUBSTR(:question_preview, 1, 400), SUBSTR(:error_message, 1, 4000));
END;]');

    ------------------------------------------------------------------ usage: remaining limits per model (no api_key!)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'usage/providers');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'usage/providers', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[SELECT * FROM ai_provider_usage_v ORDER BY priority_order]');

    ------------------------------------------------------------------ usage: one user (today + month + quota)
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'usage/user/:user_id');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'usage/user/:user_id', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[SELECT * FROM ai_user_usage_v WHERE user_id = :user_id]');

    ------------------------------------------------------------------ usage: per day for the dashboard   ?days=30&user_id=
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'usage/daily');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'usage/daily', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[
SELECT TO_CHAR(CAST(created_at AT TIME ZONE 'Asia/Karachi' AS DATE), 'YYYY-MM-DD') AS day,
       provider_id,
       MAX(model_name)                                      AS model_name,
       COUNT(*)                                             AS requests,
       SUM(prompt_tokens)                                   AS prompt_tokens,
       SUM(completion_tokens)                               AS completion_tokens,
       SUM(total_tokens)                                    AS total_tokens,
       SUM(cost_usd)                                        AS cost_usd,
       COUNT(CASE WHEN status <> 'OK' THEN 1 END)           AS failures,
       ROUND(AVG(latency_ms))                               AS avg_latency_ms
  FROM ai_usage_log
 WHERE created_at > SYSTIMESTAMP - NUMTODSINTERVAL(NVL(TO_NUMBER(:days), 30), 'DAY')
   AND (:user_id IS NULL OR user_id = TO_NUMBER(:user_id))
 GROUP BY TO_CHAR(CAST(created_at AT TIME ZONE 'Asia/Karachi' AS DATE), 'YYYY-MM-DD'), provider_id
 ORDER BY 1, 2]');

    ------------------------------------------------------------------ usage: most expensive questions   ?days=30
    ORDS.DEFINE_TEMPLATE(p_module_name => 'AI', p_pattern => 'usage/top');
    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI', p_pattern => 'usage/top', p_method => 'GET',
        p_source_type => 'json/collection',
        p_source      => q'[
SELECT l.created_at, l.user_id, u.username, l.model_name, l.call_type, l.status,
       l.prompt_tokens, l.completion_tokens, l.total_tokens, l.cost_usd, l.latency_ms, l.question_preview
  FROM ai_usage_log l
  LEFT JOIN ai_users u ON u.user_id = l.user_id
 WHERE l.created_at > SYSTIMESTAMP - NUMTODSINTERVAL(NVL(TO_NUMBER(:days), 30), 'DAY')
 ORDER BY l.total_tokens DESC
 FETCH FIRST 25 ROWS ONLY]');

    COMMIT;
END;
