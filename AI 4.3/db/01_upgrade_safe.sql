-- 6) Views: remaining limits per provider, usage per user
--    Daily limits use a rolling 24h window (Groq/OpenRouter limits replenish continuously).
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW ai_provider_usage_v AS
SELECT p.provider_id,
       p.provider_name,
       p.model_name,
       p.is_active,
       p.priority_order,
       p.plan_tier,
       p.daily_token_limit,
       p.daily_request_limit,
       p.tokens_per_minute,
       p.requests_per_minute,
       p.monthly_budget_usd,
       NVL(d.tokens_24h, 0)    AS tokens_24h,
       NVL(d.requests_24h, 0)  AS requests_24h,
       NVL(d.failures_24h, 0)  AS failures_24h,
       NVL(m.tokens_month, 0)  AS tokens_month,
       NVL(m.cost_month, 0)    AS cost_month,
       CASE WHEN p.daily_token_limit   IS NOT NULL THEN GREATEST(p.daily_token_limit   - NVL(d.tokens_24h, 0), 0)   END AS tokens_left_24h,
       CASE WHEN p.daily_request_limit IS NOT NULL THEN GREATEST(p.daily_request_limit - NVL(d.requests_24h, 0), 0) END AS requests_left_24h,
       CASE WHEN p.monthly_budget_usd  IS NOT NULL THEN GREATEST(p.monthly_budget_usd  - NVL(m.cost_month, 0), 0)   END AS budget_left_month,
       l.rl_remaining_req AS last_rl_remaining_req,
       l.rl_remaining_tok AS last_rl_remaining_tok,
       l.status           AS last_status,
       l.created_at       AS last_call_at
  FROM ai_providers p
  LEFT JOIN (SELECT provider_id,
                    SUM(total_tokens)                                          AS tokens_24h,
                    COUNT(CASE WHEN status <> 'RATE_LIMITED' THEN 1 END)       AS requests_24h,
                    COUNT(CASE WHEN status IN ('FAILED','RATE_LIMITED') THEN 1 END) AS failures_24h
               FROM ai_usage_log
              WHERE created_at > SYSTIMESTAMP - INTERVAL '1' DAY
              GROUP BY provider_id) d ON d.provider_id = p.provider_id
  LEFT JOIN (SELECT provider_id, SUM(total_tokens) AS tokens_month, SUM(cost_usd) AS cost_month
               FROM ai_usage_log
              WHERE created_at >= TRUNC(SYSDATE, 'MM')
              GROUP BY provider_id) m ON m.provider_id = p.provider_id
  LEFT JOIN (SELECT provider_id, rl_remaining_req, rl_remaining_tok, status, created_at
               FROM (SELECT u.*, ROW_NUMBER() OVER (PARTITION BY provider_id ORDER BY created_at DESC) rn
                       FROM ai_usage_log u)
              WHERE rn = 1) l ON l.provider_id = p.provider_id;

CREATE OR REPLACE VIEW ai_user_usage_v AS
SELECT us.user_id,
       us.username,
       us.is_admin,
       us.daily_token_quota,
       NVL(d.tokens_24h, 0)   AS tokens_24h,
       NVL(d.requests_24h, 0) AS requests_24h,
       NVL(m.tokens_month, 0) AS tokens_month,
       NVL(m.cost_month, 0)   AS cost_month,
       CASE WHEN us.daily_token_quota IS NOT NULL THEN GREATEST(us.daily_token_quota - NVL(d.tokens_24h, 0), 0) END AS quota_left_24h
  FROM ai_users us
  LEFT JOIN (SELECT user_id, SUM(total_tokens) AS tokens_24h, COUNT(*) AS requests_24h
               FROM ai_usage_log
              WHERE created_at > SYSTIMESTAMP - INTERVAL '1' DAY
              GROUP BY user_id) d ON d.user_id = us.user_id
  LEFT JOIN (SELECT user_id, SUM(total_tokens) AS tokens_month, SUM(cost_usd) AS cost_month
               FROM ai_usage_log
              WHERE created_at >= TRUNC(SYSDATE, 'MM')
              GROUP BY user_id) m ON m.user_id = us.user_id;

